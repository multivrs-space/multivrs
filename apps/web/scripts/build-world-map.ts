/**
 * Generates public/maps/world-110m.svg (one projected path per country, id =
 * ISO 3166-1 alpha-2, the code Cloudflare reports in analytics) and
 * src/features/dashboard/lib/world-map.data.ts (names and projected boxes).
 *
 *   bun scripts/build-world-map.ts
 *
 * Source: Natural Earth 1:110m via world-atlas. Projection: Natural Earth I.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import type { Feature, Geometry } from "geojson";
import countries from "i18n-iso-countries";
import { feature } from "topojson-client";
import type { GeometryCollection, Topology } from "topojson-specification";
import atlas from "world-atlas/countries-110m.json" with { type: "json" };

const WIDTH = 960;
const HEIGHT = 470;
/** Countries Natural Earth ships without a numeric ISO code. */
const NAMED_CODES: Record<string, string> = { Kosovo: "XK" };
const SKIP = new Set(["AQ"]);
const SHORT_NAMES: Record<string, string> = {
  BO: "Bolivia",
  CD: "DR Congo",
  CZ: "Czechia",
  GB: "United Kingdom",
  IR: "Iran",
  KP: "North Korea",
  KR: "South Korea",
  LA: "Laos",
  MD: "Moldova",
  MK: "North Macedonia",
  PS: "Palestine",
  RU: "Russia",
  SY: "Syria",
  TW: "Taiwan",
  TZ: "Tanzania",
  US: "United States",
  VE: "Venezuela",
  VN: "Vietnam",
};
/** Countries cut by the antimeridian, whose mainland box would span the map. */
const BOX_OVERRIDES: Record<string, [number, number, number, number]> = {
  RU: [525, 40, 866, 143],
};

const topology = atlas as unknown as Topology<{
  countries: GeometryCollection<{ name: string }>;
}>;
const collection = feature(topology, topology.objects.countries);

const shapes = collection.features.flatMap((shape) => {
  const name = shape.properties?.name ?? "";
  const iso2 =
    (shape.id !== undefined
      ? countries.numericToAlpha2(String(shape.id).padStart(3, "0"))
      : undefined) ?? NAMED_CODES[name];
  if (!iso2 || SKIP.has(iso2)) return [];
  // Natural Earth abbreviates ("Bosnia and Herz."); prefer the ISO name, or
  // the short form people actually say.
  const label = SHORT_NAMES[iso2] ?? countries.getName(iso2, "en") ?? name;
  return [{ iso2, name: label, shape }];
});

const projection = geoNaturalEarth1().fitExtent(
  [
    [4, 4],
    [WIDTH - 4, HEIGHT - 4],
  ],
  { type: "FeatureCollection", features: shapes.map((entry) => entry.shape) },
);
const path = geoPath(projection).digits(0);

/** Drop consecutive duplicate points that integer rounding leaves behind. */
function compact(d: string): string {
  let previous = "";
  return d
    .split(/(?=[MLZ])/)
    .filter((command) => {
      if (command.startsWith("L") && command === previous) return false;
      previous = command.startsWith("M") ? `L${command.slice(1)}` : command;
      return true;
    })
    .join("");
}

/**
 * The country's largest polygon, so boxes and label anchors sit on the
 * mainland rather than spanning overseas territories (France and French
 * Guiana, the US and Alaska).
 */
function mainland(shape: Feature<Geometry>): Feature<Geometry> {
  if (shape.geometry.type !== "MultiPolygon") return shape;
  const polygons = shape.geometry.coordinates.map(
    (coordinates): Feature<Geometry> => ({
      type: "Feature",
      properties: {},
      geometry: { type: "Polygon", coordinates },
    }),
  );
  return polygons.reduce((largest, polygon) =>
    path.area(polygon) > path.area(largest) ? polygon : largest,
  );
}

const rows = shapes
  .map(({ iso2, name, shape }) => {
    const d = compact(path(shape) ?? "");
    const [[x0, y0], [x1, y1]] = path.bounds(mainland(shape));
    const box =
      BOX_OVERRIDES[iso2] ?? [x0, y0, x1, y1].map((value) => Math.round(value));
    return { iso2, name, d, box };
  })
  .filter((row) => row.d)
  .sort((left, right) => left.iso2.localeCompare(right.iso2));

/* 1. The shapes, as a static SVG the browser caches once and pages reference
   with <use href="/maps/world-110m.svg#NG">. Paths carry no fill or stroke so
   the referencing <use> styles them. */
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}"><g id="world">${rows
  .map((row) => `<path id="${row.iso2}" d="${row.d}"/>`)
  .join("")}</g></svg>
`;
const svgTarget = join(import.meta.dir, "../public/maps/world-110m.svg");
mkdirSync(dirname(svgTarget), { recursive: true });
writeFileSync(svgTarget, svg);

/* 2. Names and boxes for the page, so it can zoom to where traffic is. */
const lines = rows.map(
  (row) =>
    `  ${row.iso2}: { name: ${JSON.stringify(row.name)}, box: [${row.box.join(", ")}] },`,
);

const source = `// Generated by scripts/build-world-map.ts from Natural Earth 1:110m (public
// domain) via world-atlas. Do not edit by hand. Shapes live in
// public/maps/world-110m.svg; this module only knows names and boxes.

export const WORLD_MAP_SIZE = { width: ${WIDTH}, height: ${HEIGHT} } as const;

export const WORLD_MAP_SRC = "/maps/world-110m.svg";

export interface WorldCountry {
  name: string;
  /** Projected bounding box: x0, y0, x1, y1. */
  box: readonly [number, number, number, number];
}

/** Keyed by ISO 3166-1 alpha-2, the code Cloudflare reports in analytics. */
export const WORLD_COUNTRIES: Readonly<Record<string, WorldCountry>> = {
${lines.join("\n")}
};
`;

const target = join(
  import.meta.dir,
  "../src/features/dashboard/lib/world-map.data.ts",
);
writeFileSync(target, source);
process.stdout.write(
  `Wrote ${rows.length} countries to ${svgTarget} and ${target}\n`,
);
